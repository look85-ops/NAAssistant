# -*- coding: utf-8 -*-
import sys
from docx import Document
from docx.shared import Pt, RGBColor

def build_doc():
    doc = Document()

    style = doc.styles['Normal']
    font = style.font
    font.name = 'Calibri'
    font.size = Pt(11)

    def add_h(text, level=1):
        h = doc.add_heading(text, level=level)
        for run in h.runs:
            run.font.color.rgb = RGBColor(0, 51, 102)
        return h

    def add_p(text, bold=False, italic=False):
        p = doc.add_paragraph()
        run = p.add_run(text)
        run.bold = bold
        run.italic = italic
        return p

    def add_t(headers, rows):
        table = doc.add_table(rows=1 + len(rows), cols=len(headers))
        table.style = 'Light Grid Accent 1'
        for i, h in enumerate(headers):
            cell = table.rows[0].cells[i]
            cell.text = h
            for p in cell.paragraphs:
                for run in p.runs:
                    run.bold = True
                    run.font.size = Pt(9)
        for r, row in enumerate(rows):
            for c, val in enumerate(row):
                cell = table.rows[r+1].cells[c]
                cell.text = val
                for p in cell.paragraphs:
                    for run in p.runs:
                        run.font.size = Pt(9)
        return table

    # 1. Geopolitical (конспект из v4)
    add_h('1. Геополитический прогноз для Беларуси (горизонт 2–5 лет)')
    add_p('Дата актуализации: 3 августа 2026 года.', italic=True)
    add_p('Беларусь — «привязанный актив» России, глубокий тыл и одновременно передовой ядерный бастион. На август 2026 СВО идёт четвёртый год, конца активной фазе не видно.')
    add_p('Ключевые события лета 2026: ракета в Польше (НАТО), массированные удары по Украине и удары дронами по РФ, новый пакет санкций США, обсуждение призыва в ФРГ.',)
    add_p('Общий вектор: расширение географии ударов и рост риска прямого столкновения РФ–НАТО.', bold=True)
    add_t([
        'Сценарий','Вероятность (было → стало)','Суть','Последствия для Минска и рынка недвижимости'
    ],[
        ['1. Глубокая интеграция и тыловая база','65–70% → 50–55%','РБ не вступает в войну напрямую; размещение ТЯО РФ сохраняется.','Тыл, но риск ответного удара при глобальной эскалации. Рынок недвижимости — стагнация, низкая ликвидность.'],
        ['2. Втягивание','20–25% → 35–40%','Открытие фронта, мобилизация, удары по территории.','Минск становится прифронтовым. Границы закрыты, выезд мужчин — под вопросом. Ликвидность жилья → 0.'],
        ['3. Мягкая буферизация','5–10%','Частичная разрядка, попытки диалога.','Краткосрочный рост цен и ликвидности, но структурная слабость сохраняется.']
    ])
    add_p('Сценарий «Втягивание» уже не маргинален. Риск того, что Минск станет прифронтовым, вырос почти вдвое.', bold=True)

    # 2. Minsk move (конспект)
    add_h('2. Переезд из Москвы в Минск — оценка решения')
    add_p('Контекст: переезд семьи из-за работы мужа; учёба в БГАИ (заочная, 2 года) как фактор укоренения, но не жёсткий якорь — при эскалации оставляется.',)
    add_p('Вывод: ехать рационально, но ускорить подготовку «плана Б» и разведку альтернативных юрисдикций.', bold=True)

    # 3. No buy now
    add_h('3. Покупка жилья сейчас — категорическое «НЕТ»')
    add_p('Неликвид, санкции, риск эскалации и потеря мобильности. Аренда > покупка.', bold=True)

    # 4. Post-SVO → условия
    add_h('4. Покупка в Минске: при каких условиях это перестаёт быть ошибкой')
    add_p('Не «когда закончится СВО», а «при каких условиях». Два варианта:', bold=True)
    add_t(['Сценарий','Когда','Условия','Риск'],[
        ['Устойчивая деэскалация','Через 18+ мес. стабильности','Нет инцидентов на границах, частичное снятие санкций, ликвидность рынка','Средний'],
        ['Осознанное «остаёмся»','В любой момент','≤5–10% капитала, без кредитов, психологическая готовность списать в ноль','Высокий'],
        ['Все прочие случаи','—','Аренда — единственный рациональный выбор','Максимальный']
    ])

    # 5. Decision table
    add_h('5. Итоговое резюме в таблице решений')
    add_t(['Вопрос','Рекомендация','Ключевое условие'],[
        ['Ехать ли в Минск сейчас?','Да','Сохранять мобильность, ускорить «план Б»'],
        ['Покупать ли квартиру сейчас?','Нет','Аренда даёт гибкость и безопасность'],
        ['Когда можно будет купить?','Только при деэскалации (18+ мес.) или «остаёмся навсегда»','Только свободные деньги'],
        ['Как покупать, если хочется своё?','Только как «минимальный якорь»','Малогабаритное жильё в центре, без кредитов']
    ])

    # 6. Emigration — expanded
    add_h('6. Эмиграция и сохранение капитала: стратегия и альтернативы (актуализация 03.08.2026)')
    add_p('Принцип: не класть всё в одну корзину. ОАЭ — сильный «сейф» для части капитала; Аргентина — лучший «паспорт» по срокам; «место для жизни» — подбираем под ценности и профессию.', bold=True)
    add_p('Санкционный контекст: новые тарифы США на РФ/Иран; одновременно под давлением три пролива (Ормуз, Баб-эль-Мандеб, Чёрное море).', italic=True)

    add_p('Базовый сет (ядро):', bold=True)
    add_t(['Роль','Страна','Почему','Порог/условия','Риски (2026)'],[
        ['Сейф (часть капитала)','ОАЭ (Дубай)','Нейтралитет, нулевые налоги, ликвидная недвижимость, антихрупкий рынок','Golden Visa: недвижимость от ~$545k; инвестировать ≤40–50% капитала','Ормуз: логистические риски; см. 6А'],
        ['Паспорт','Аргентина','Гражданство ~за 2 года, без крупных вложений; культурная среда','ВНЖ при доходе; гражданство после проживания','Инфляция, экономическая нестабильность'],
        ['Место для жизни','Таиланд','Комфорт, медицина, доступные кондо, долгосрочные визы','Кондо от ~$100k; визы 5–20 лет','Нет пути к гражданству, визовая зависимость']
    ])

    add_h('6А. Ормузский пролив — что значит для ОАЭ', level=2)
    add_p('Коротко: риск реален, но не фатален. ОАЭ смягчает через порт Фуджейра (обход Ормуза) и ненефтяную экономику. Правила: 1) не все деньги в Дубай; 2) брать ликвидные объекты; 3) диверсифицировать по странам.', italic=True)

    add_h('6Б. Альтернативы по ролям: кандидаты на разведку', level=2)

    add_p('6Б.1 Место для жизни (альтернатива Таиланду):', bold=True)
    add_t(['Страна','Почему рассмотреть','Порог/правовой путь (проверить на момент подачи)','Риски/оговорки'],[
        ['Сербия','Славянская культура, близость к ЕС, активная творческая сцена (Белград)','ВНЖ через бизнес/работу/недвижимость; гражданство — долгий горизонт','Перегретый рынок из-за притока мигрантов; путь к паспорту не быстрый'],
        ['Турция (Стамбул/Измир)','Крупный рынок, кино/театры, удобная логистика','Гражданство через инвестиции в недвижимость (порог менялся, исторически ~$400k)','Инфляция, политические риски'],
        ['Португалия/Испания','Климат, культура, ЕС; долгосрочно — паспорт','Инвест.программы менялись; возможны пути без недвижимости','Бюрократия, стоимость, сроки 5–10 лет'],
        ['Черногория','Красногория, близость к ЕС, развивающийся рынок','ВНЖ через бизнес/недвижимость; гражданство ограничено','Малый рынок, сезонность'],
        ['Грузия (осторожно)','Простота быта, автономия, IT/креатив-сцена','Длительные безвизы/ВНЖ, низкий порог входа','Политические риски, близость к РФ']
    ])

    add_p('6Б.2 Паспорт (альтернатива Аргентине):', bold=True)
    add_t(['Страна','Путь к паспорту (оценка)','Почему это вариант','Риски/оговорки'],[
        ['Чили','~5 лет проживания','Стабильность, развитая экономика','Дороже, дальше, строгие правила'],
        ['Уругвай','~3–5 лет проживания (семья быстрее)','Стабильная демократия, «Швейцария Латинской Америки»','Стоимость жизни выше средних по региону'],
        ['Турция','Гражданство за инвестиции','Быстро и понятно юридически','Стоимость и политический риск'],
        ['Парагвай','Исторически 3 года, правила менялись','Невысокий порог входа','Частые изменения иммиграционных правил — проверять актуальность']
    ])

    add_p('6Б.3 Сейф (альтернатива ОАЭ):', bold=True)
    add_t(['Инструмент/юрисдикция','Идея','Почему это разумно','Оговорки'],[
        ['Распределённые валютные счета (вне РФ/РБ)','Разложить ликвидность по банкам/странам','Доступ к деньгам без продажи активов','KYC и ограничения по гражданству — готовить пакет документов'],
        ['Биржевые ETF (offshore)','Часть капитала держать в ликвидных инструментах','Глобальная диверсификация','Регуляторные риски и доступ для граждан РФ — уточнять'],
        ['Кастодиальная/самокастодиальная крипта','Хедж от банковских блокировок','Высокая мобильность и доступность','Волатильность и операционные риски']
    ])

    add_p('Как выбирать кандидатов на разведку:', bold=True)
    add_p('— Возьми по одному из двух регионов: «Европа рядом» (Сербия/Турция) и «ЛатАм» (Аргентина/Уругвай).')
    add_p('— Поедьте на 2–3 недели: проверьте бытовые мелочи, медицину, транспорт, комьюнити. Фактура важнее форумов.')
    add_p('— Цель разведки — не «влюбиться», а составить чек-лист «годится/не годится» по 10 пунктам (бюджет, визы, медицина, язык, климат, комьюнити, безопасность, школа/универы, рынок жилья, интернет).')

    # 7. Roadmap (конспект)
    add_h('7. Пошаговая дорожная карта (два трека, ускорение)')
    add_p('6–12 месяцев на подготовку путей отхода: разведпоездки, ВНЖ, распределение капитала.', bold=True)

    # 8. Final
    add_h('8. Финальный вывод (03.08.2026)')
    add_p('Три правила: 1) диверсификация стран и активов; 2) два параллельных трека (Минск и отход) без самообмана; 3) аренда вместо покупки в Минске.', bold=True)

    return doc

